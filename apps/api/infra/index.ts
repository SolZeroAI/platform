export type ApiSecretInput = string | Output.Output<Redacted.Redacted<string>>

export interface ApiInfraEnv {
  readonly S0_PROVIDER_LAYER: "live" | "mock"
  readonly S0_CONFIG_FILE: string
  readonly S0_CONFIG_ADMIN: AdminConfig
  readonly S0_CONFIG_AUTH: S0AuthConfig
  readonly S0_CONFIG_CLOUDFLARE_AI_GATEWAY: S0CloudflareAiGatewayConfig
  readonly S0_CONFIG_LITELLM?: S0LitellmConfig
  readonly S0_CONFIG_MCPCF?: S0McpcfConfig
  readonly S0_DEPLOYMENT_CONFIG_DIGEST: string
  readonly configSecretBindings: Readonly<Record<string, ApiSecretInput>>
  readonly cloudflareAiGatewayProviderKeySecrets: Readonly<
    Partial<Record<CloudflareAiGatewayByokProvider, ApiSecretInput>>
  >
  readonly MCPCF_PROXY_SIGNING_SECRET: ApiSecretInput
  readonly TOKEN_ENCRYPTION_KEY: ApiSecretInput
  readonly REPO_SECRETS_ENCRYPTION_KEY: ApiSecretInput
  readonly BETTER_AUTH_SECRET: ApiSecretInput
  readonly GITHUB_APP_CLIENT_ID: string
  readonly GITHUB_APP_CLIENT_SECRET: ApiSecretInput
  readonly GITHUB_APP_ID: string
  readonly GITHUB_APP_PRIVATE_KEY: ApiSecretInput
  readonly GITHUB_APP_SLUG: string
  readonly GITHUB_APP_WEBHOOK_SECRET: ApiSecretInput
  readonly SLACK_TOKEN: ApiSecretInput
  readonly CF_AI_SEARCH_SERVICE_TOKEN_ID: string
}

function secretValue(
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
  reference: SecretReference | null | undefined,
): ApiSecretInput {
  return reference ? (secretBindings[reference.env] ?? "") : ""
}

function configuredStringSecretValue(
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
  reference: SecretReference | null | undefined,
): string {
  const value = secretValue(secretBindings, reference)
  if (typeof value !== "string") {
    throw new Error(`${reference?.env ?? "Secret"} cannot be generated by Alchemy`)
  }
  return value
}

export function getApiInfraEnv(
  config: S0ResolvedConfig,
  configurationFile: string,
  deploymentConfigDigest: string,
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
): ApiInfraEnv {
  const credentialSignInEnabled = Object.values(config.auth.providers).some(
    (provider) =>
      provider.kind === "credential" && provider.enabled && provider.capabilities.signIn,
  )
  if (credentialSignInEnabled && config.admins.adminEmails.length === 0) {
    throw new Error(
      "The active stage config admins.adminEmails must contain at least one address when credential sign-in is enabled",
    )
  }
  if (credentialSignInEnabled) {
    const adminPasswordReference = config.auth.adminPassword
    if (!adminPasswordReference) {
      throw new Error("auth.adminPassword is required when credential sign-in is enabled")
    }
    const adminPassword = secretValue(secretBindings, adminPasswordReference)
    if (typeof adminPassword === "string" && adminPassword.length < 12) {
      throw new Error(`${adminPasswordReference.env} must contain at least 12 characters`)
    }
  }
  const mcpcfProxySigningSecret = secretValue(
    secretBindings,
    config.security.mcpcfProxySigningSecret,
  )
  if (
    typeof mcpcfProxySigningSecret === "string" &&
    mcpcfProxySigningSecret.length < MCPCF_PROXY_SIGNING_SECRET_MIN_LENGTH
  ) {
    throw new Error(
      `${config.security.mcpcfProxySigningSecret.env} must contain at least ${MCPCF_PROXY_SIGNING_SECRET_MIN_LENGTH} characters`,
    )
  }
  const githubApp = config.integrations.githubApp
  const slack = config.integrations.slack
  const configSecretBindings = Object.fromEntries(
    s0RuntimeSecretReferences(config).map((reference) => [
      reference.env,
      secretValue(secretBindings, reference),
    ]),
  )
  const cloudflareAiGatewayProviderKeySecrets = Object.fromEntries(
    Object.entries(config.aiProviders.cloudflareAiGateway.providerKeys ?? {}).map(
      ([providerId, reference]) => [providerId, secretValue(secretBindings, reference)],
    ),
  )
  return {
    S0_PROVIDER_LAYER: "live",
    S0_CONFIG_FILE: configurationFile,
    S0_CONFIG_ADMIN: config.admins,
    S0_CONFIG_AUTH: config.auth,
    S0_CONFIG_CLOUDFLARE_AI_GATEWAY: config.aiProviders.cloudflareAiGateway,
    ...(config.aiProviders.litellm ? { S0_CONFIG_LITELLM: config.aiProviders.litellm } : {}),
    ...(config.mcpcf ? { S0_CONFIG_MCPCF: config.mcpcf } : {}),
    S0_DEPLOYMENT_CONFIG_DIGEST: deploymentConfigDigest,
    configSecretBindings,
    cloudflareAiGatewayProviderKeySecrets,
    MCPCF_PROXY_SIGNING_SECRET: mcpcfProxySigningSecret,
    TOKEN_ENCRYPTION_KEY: secretValue(secretBindings, config.security.tokenEncryptionKey),
    REPO_SECRETS_ENCRYPTION_KEY: secretValue(
      secretBindings,
      config.security.repositorySecretsEncryptionKey,
    ),
    BETTER_AUTH_SECRET: secretValue(secretBindings, config.security.betterAuthSecret),
    GITHUB_APP_CLIENT_ID: githubApp.enabled ? githubApp.clientId : "",
    GITHUB_APP_CLIENT_SECRET: githubApp.enabled
      ? secretValue(secretBindings, githubApp.clientSecret)
      : "",
    GITHUB_APP_ID: githubApp.enabled ? githubApp.appId : "",
    GITHUB_APP_PRIVATE_KEY: githubApp.enabled
      ? secretValue(secretBindings, githubApp.privateKey)
      : "",
    GITHUB_APP_SLUG: githubApp.enabled ? githubApp.slug : "",
    GITHUB_APP_WEBHOOK_SECRET:
      githubApp.enabled && githubApp.webhookSecret
        ? secretValue(secretBindings, githubApp.webhookSecret)
        : "",
    SLACK_TOKEN: slack.enabled ? secretValue(secretBindings, slack.botToken) : "",
    CF_AI_SEARCH_SERVICE_TOKEN_ID: configuredStringSecretValue(
      secretBindings,
      config.aiSearch.serviceTokenId,
    ),
  }
}

