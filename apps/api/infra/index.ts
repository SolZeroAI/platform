function secretInput(
  value: string | Output.Output<Redacted.Redacted<string>>,
): Redacted.Redacted<string> {
  return Match.value(value).pipe(
    Match.when(Match.string, Redacted.make),
    Match.orElse((output) => output),
  ) as Redacted.Redacted<string>
}

function jsonBinding(value: unknown): Schema.Json {
  // Alchemy's JSON binding type requires an index signature, while our decoded
  // configuration DTOs intentionally use exact interfaces. The compiler has
  // already schema-decoded these values before they reach this boundary.
  return value as Schema.Json
}

function workflowActionsBinding(
  service: string,
): Cloudflare.WorkerEntrypointBinding<WorkflowActionsEntrypoint> {
  return {
    BindingType: "Cloudflare.WorkerEntrypointBinding",
    service,
    entrypoint: "WorkflowActions",
  }
}

function dynamicWorkflowBinding(appName: string, stageMetadata: StageMetadata, workerName: string) {
  return Cloudflare.Workflow(getDynamicWorkflowName(appName, stageMetadata.name), {
    className: DYNAMIC_WORKFLOW_CLASS_NAME,
    scriptName: workerName,
  })
}

const MAX_USER_VARIABLE_BINDINGS = 60
const MAX_VARIABLE_BINDING_BYTES = 4_500
const MAX_SECRET_BINDING_BYTES = 5_000

function bindingSize(value: unknown): number {
  const serialized = typeof value === "string" ? value : JSON.stringify(value)
  return new TextEncoder().encode(serialized).byteLength
}

function validateApiVariableBindings(
  variables: Readonly<Record<string, unknown>>,
  secrets: Readonly<Record<string, ApiSecretInput>>,
): void {
  const bindingNames = new Set([...Object.keys(variables), ...Object.keys(secrets)])
  if (bindingNames.size > MAX_USER_VARIABLE_BINDINGS) {
    throw new Error(
      `API Worker configuration defines ${bindingNames.size} variables and secrets; the s0 deployment budget is ${MAX_USER_VARIABLE_BINDINGS} to reserve capacity for Alchemy-managed bindings`,
    )
  }
  for (const [name, value] of Object.entries(variables)) {
    const size = bindingSize(value)
    if (size > MAX_VARIABLE_BINDING_BYTES) {
      throw new Error(
        `API Worker variable ${name} is ${size} bytes; split it before the ${MAX_VARIABLE_BINDING_BYTES}-byte s0 deployment budget`,
      )
    }
  }
  for (const [name, value] of Object.entries(secrets)) {
    if (typeof value !== "string") continue
    const size = bindingSize(value)
    if (size > MAX_SECRET_BINDING_BYTES) {
      throw new Error(
        `API Worker secret ${name} is ${size} bytes; Cloudflare secrets must not exceed ${MAX_SECRET_BINDING_BYTES} bytes`,
      )
    }
  }
}

function createApiBindings(options: CreateApiBindingsOptions) {
  const {
    appName,
    stageMetadata,
    deploymentMetadata,
    cloudflareAccountId,
    agentResources,
    agentContainers,
    aiGateway,
    env,
    workerName,
  } = options

  const variables = {
    STAGE: stageMetadata.name,
    WORKER_NAME: workerName,
    APP_VERSION: deploymentMetadata.appVersion,
    COMMIT_SHA: deploymentMetadata.commitSha,
    S0_PROVIDER_LAYER: env.S0_PROVIDER_LAYER,
    S0_CONFIG_FILE: env.S0_CONFIG_FILE,
    S0_STAGE_METADATA: jsonBinding({
      _tag: stageMetadata._tag,
      name: stageMetadata.name,
      app: stageMetadata.app,
      infra: stageMetadata.infra,
    }),
    S0_CONFIG_ADMIN: jsonBinding(env.S0_CONFIG_ADMIN),
    S0_CONFIG_AUTH: jsonBinding(env.S0_CONFIG_AUTH),
    S0_CONFIG_CLOUDFLARE_AI_GATEWAY: jsonBinding(env.S0_CONFIG_CLOUDFLARE_AI_GATEWAY),
    ...(env.S0_CONFIG_LITELLM ? { S0_CONFIG_LITELLM: jsonBinding(env.S0_CONFIG_LITELLM) } : {}),
    ...(env.S0_CONFIG_MCPCF ? { S0_CONFIG_MCPCF: jsonBinding(env.S0_CONFIG_MCPCF) } : {}),
    S0_DEPLOYMENT_CONFIG_DIGEST: env.S0_DEPLOYMENT_CONFIG_DIGEST,
    CLOUDFLARE_ACCOUNT_ID: cloudflareAccountId,
    GITHUB_APP_CLIENT_ID: env.GITHUB_APP_CLIENT_ID,
    GITHUB_APP_ID: env.GITHUB_APP_ID,
    GITHUB_APP_SLUG: env.GITHUB_APP_SLUG,
    CF_AI_SEARCH_SERVICE_TOKEN_ID: env.CF_AI_SEARCH_SERVICE_TOKEN_ID,
  }
  const fixedSecrets = {
    MCPCF_PROXY_SIGNING_SECRET: env.MCPCF_PROXY_SIGNING_SECRET,
    TOKEN_ENCRYPTION_KEY: env.TOKEN_ENCRYPTION_KEY,
    REPO_SECRETS_ENCRYPTION_KEY: env.REPO_SECRETS_ENCRYPTION_KEY,
    BETTER_AUTH_SECRET: env.BETTER_AUTH_SECRET,
    GITHUB_APP_CLIENT_SECRET: env.GITHUB_APP_CLIENT_SECRET,
    GITHUB_APP_PRIVATE_KEY: env.GITHUB_APP_PRIVATE_KEY,
    GITHUB_APP_WEBHOOK_SECRET: env.GITHUB_APP_WEBHOOK_SECRET,
    SLACK_TOKEN: env.SLACK_TOKEN,
    ...(aiGateway ? { CLOUDFLARE_AI_GATEWAY_RUN_TOKEN: aiGateway.runToken } : {}),
  }
  const secrets = { ...env.configSecretBindings, ...fixedSecrets }
  validateApiVariableBindings(variables, secrets)

  return {
    ...variables,

    ...(aiGateway
      ? {
          AI_GATEWAY: aiGateway.resource,
          AI_GATEWAY_ID: aiGateway.gatewayId,
          AI_GATEWAY_SECRETS_STORE_ID: aiGateway.secretsStoreId,
        }
      : {}),

    // Worker bindings
    WORKFLOW_LOADER: Cloudflare.WorkerLoader(),
    ...(options.dev ? {} : { BROWSER: Cloudflare.Browser() }),
    SESSION: agentResources.sessionNamespace,
    ISOLATE_SESSION: agentResources.isolateSessionNamespace,
    WORKFLOW_ALARM: agentResources.workflowAlarmNamespace,
    DYNAMIC_WORKFLOW: dynamicWorkflowBinding(appName, stageMetadata, workerName),
    ...(agentResources.aiSearchNamespace ? { AI_SEARCH: agentResources.aiSearchNamespace } : {}),
    ...(agentResources.workflowAiSearchNamespace
      ? { WORKFLOW_AI_SEARCH: agentResources.workflowAiSearchNamespace }
      : {}),
    WORKFLOW_ACTIONS: workflowActionsBinding(workerName),
    WORKFLOW_BUCKET: agentResources.workflowBucket,
    AI_SEARCH_CONTENT_BUCKET: agentResources.aiSearchContentBucket,
    DB: agentResources.db,
    S0_CONFIG: agentResources.s0Config,
    REPOS_CACHE: agentResources.repoCache,
    USER_WORKFLOW_KV: agentResources.userWorkflowKv,
    WORKFLOW_SESSION_RESPONSE_CACHE: agentResources.workflowSessionResponseCache,
    OPENCODE_AGENT: agentContainers.opencode,
    CODEX_AGENT: agentContainers.codex,
    CLAUDE_CODE_AGENT: agentContainers.claudeCode,
    AGENT_SKILLS: agentResources.skillsBucket,
    AUTH_SIGN_IN_RATE_LIMIT: Cloudflare.RateLimit("AUTH_SIGN_IN_RATE_LIMIT", {
      namespaceId: 1001,
      simple: { limit: 10, period: 60 },
    }),

    ...Object.fromEntries(
      Object.entries(env.configSecretBindings).map(([name, value]) => [name, secretInput(value)]),
    ),
    MCPCF_PROXY_SIGNING_SECRET: secretInput(fixedSecrets.MCPCF_PROXY_SIGNING_SECRET),
    TOKEN_ENCRYPTION_KEY: secretInput(fixedSecrets.TOKEN_ENCRYPTION_KEY),
    REPO_SECRETS_ENCRYPTION_KEY: secretInput(fixedSecrets.REPO_SECRETS_ENCRYPTION_KEY),
    BETTER_AUTH_SECRET: secretInput(fixedSecrets.BETTER_AUTH_SECRET),
    GITHUB_APP_CLIENT_SECRET: secretInput(fixedSecrets.GITHUB_APP_CLIENT_SECRET),
    GITHUB_APP_PRIVATE_KEY: secretInput(fixedSecrets.GITHUB_APP_PRIVATE_KEY),
    GITHUB_APP_WEBHOOK_SECRET: secretInput(fixedSecrets.GITHUB_APP_WEBHOOK_SECRET),
    SLACK_TOKEN: secretInput(fixedSecrets.SLACK_TOKEN),
    ...(aiGateway
      ? {
          CLOUDFLARE_AI_GATEWAY_RUN_TOKEN: secretInput(aiGateway.runToken),
        }
      : {}),
  }
}

export type ApiWorkerBindingResources = ReturnType<typeof createApiBindings>

export function createApi(options: CreateApiOptions) {
  const {
    appName,
    stageMetadata,
    deploymentMetadata,
    dev,
    cloudflareAccountId,
    agentResources,
    agentContainers,
    agentContainerApplications,
    aiGateway,
    env,
  } = options

  const __filename = fileURLToPath(import.meta.url)
  const __dirname = dirname(__filename)
  const entrypoint = resolve(__dirname, "../index.ts")

  // We replicate Alchemy's naming scheme so we can provide it as a binding env var
  const workerName = `${getApiResourceName(appName)}-${stageMetadata.name}`

  const devConfig = Match.value(dev).pipe(
    Match.when(true, () => ({ dev: { port: 1337 } })),
    Match.orElse(() => ({})),
  )
  const [primaryDomain, ...domainAliases] = stageMetadata.infra.apiDomains
  const domainConfig = Match.value(primaryDomain).pipe(
    Match.when(Match.string, (name) => ({
      domain: {
        name,
        aliases: domainAliases,
      },
      workersDev: false as const,
    })),
    Match.orElse(() => ({})),
  )

  const api = Cloudflare.Worker("api", {
    name: workerName,
    main: entrypoint,
    compatibility: {
      date: "2026-07-21",
      flags: ["nodejs_compat"],
    },
    ...devConfig,
    observability: {
      enabled: true,
      logs: {
        enabled: true,
        destinations: [...stageMetadata.infra.apiObservabilityLogsDestinations],
        invocationLogs: false,
        headSamplingRate: stageMetadata.infra.apiObservabilityLogsHeadSamplingRate,
        persist: true,
      },
      traces: {
        enabled: true,
        destinations: [...stageMetadata.infra.apiObservabilityTracesDestinations],
        headSamplingRate: stageMetadata.infra.apiObservabilityTracesHeadSamplingRate,
        persist: true,
      },
    },
    ...domainConfig,
    crons: ["0 13 * * *", "0 14 * * *"],
    env: createApiBindings({
      appName,
      dev,
      stageMetadata,
      deploymentMetadata,
      cloudflareAccountId,
      agentResources,
      agentContainers,
      aiGateway,
      env,
      workerName,
    }),
  })

  return api.pipe(
    Effect.tap((api) =>
      bindAgentContainerRuntimes({
        api,
        agentContainerApplications,
      }),
    ),
    Effect.tap(() => Effect.log(`API available at ${stageMetadata.infra.serverUrl}`)),
  )
}

function bindAgentContainerRuntimes(options: {
  api: Cloudflare.Worker
  agentContainerApplications: AgentContainerApplications
}) {
  const { api, agentContainerApplications } = options

  return Effect.gen(function* () {
    yield* bindAgentContainerRuntime(api, agentContainerApplications.opencode, {
      logicalId: "opencode-agent",
      className: "OpenCodeAgentContainer",
    })
    yield* bindAgentContainerRuntime(api, agentContainerApplications.codex, {
      logicalId: "codex-agent",
      className: "CodexAgentContainer",
    })
    yield* bindAgentContainerRuntime(api, agentContainerApplications.claudeCode, {
      logicalId: "claude-code-agent",
      className: "ClaudeCodeAgentContainer",
    })
  })
}

function bindAgentContainerRuntime(
  api: Cloudflare.Worker,
  containerApplication: AgentContainerApplications[keyof AgentContainerApplications],
  namespaceOptions: { logicalId: string; className: string },
) {
  return Cloudflare.ContainerPlatform.bind(containerApplication).pipe(
    Effect.provideService(Self(Cloudflare.WorkerTypeId), api),
    Effect.provideService(
      Cloudflare.DurableObjectScope,
      createAgentContainerNamespace(api, namespaceOptions),
    ),
  )
}

function createAgentContainerNamespace(
  api: Cloudflare.Worker,
  options: { logicalId: string; className: string },
) {
  // oxlint-disable-next-line effect/avoid-any -- Alchemy resource type-bridge: hand-builds the DurableObject resource shape that ContainerPlatform.bind expects; Alchemy resource types are not Schema-decodable here.
  return {
    Type: "Cloudflare.DurableObject",
    LogicalId: options.logicalId,
    kind: "Cloudflare.DurableObject",
    name: options.className,
    namespaceId: api.durableObjectNamespaces.pipe(
      Output.map((namespaces) => namespaces[options.className]),
    ),
  } as unknown as Cloudflare.DurableObject
}

