function includeWhenDefined<Base extends object, Value, Extra extends object>(
  base: Base,
  value: Value,
  extra: (present: Value & {}) => Extra,
): Base & Partial<Extra> {
  const included: Base & Partial<Extra> = { ...base }

  // SAFETY: Match.defined excludes null and undefined, and Object.assign copies extra only for that present value; Partial records that those keys stay absent otherwise.
  return Match.value(value).pipe(
    Match.when(Match.defined, (present) => Object.assign(included, extra(present as Value & {}))),
    Match.orElse(() => included),
  ) as Base & Partial<Extra>
}

function includeWhenAbsent<Base extends object, Extra extends object>(
  base: Base,
  present: boolean,
  extra: () => Extra,
): Base & Partial<Extra> {
  const included: Base & Partial<Extra> = { ...base }

  // SAFETY: Object.assign copies extra only when the flag is absent; Partial records that those keys stay absent otherwise.
  return Match.value(present).pipe(
    Match.when(false, () => Object.assign(included, extra())),
    Match.orElse(() => included),
  ) as Base & Partial<Extra>
}

const invalidApiConfig = (message: string) => new ConfigValidationError({ message })

function secretValue(
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
  reference: SecretReference | null | undefined,
): ApiSecretInput {
  return Option.match(Option.fromNullishOr(reference), {
    onNone: () => "",
    onSome: ({ env }) => secretBindings[env] ?? "",
  })
}

function configuredStringSecretValue(
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
  reference: SecretReference | null | undefined,
): string {
  return Result.liftPredicate(
    secretValue(secretBindings, reference),
    P.isString,
    () => invalidApiConfig(`${reference?.env ?? "Secret"} cannot be generated by Alchemy`),
    // oxlint-disable-next-line effect/avoid-option-getorthrow -- Synchronous boundary for non-Effect callers: invalid input throws the typed error by contract.
  ).pipe(Result.getOrThrow)
}

/** A literal secret must meet its minimum length. Alchemy-generated secrets are checked by Alchemy. */
const hasMinimumLength = (value: ApiSecretInput, minimum: number) =>
  !P.isString(value) || value.length >= minimum

const validateCredentialSignIn = (
  config: S0ResolvedConfig,
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
) =>
  Result.gen(function* () {
    yield* ensureConfig(config.admins.adminEmails.length > 0, () =>
      invalidApiConfig(
        "The active stage config admins.adminEmails must contain at least one address when credential sign-in is enabled",
      ),
    )

    const adminPasswordReference = yield* Result.fromNullishOr(config.auth.adminPassword, () =>
      invalidApiConfig("auth.adminPassword is required when credential sign-in is enabled"),
    )

    yield* ensureConfig(
      hasMinimumLength(secretValue(secretBindings, adminPasswordReference), 12),
      () => invalidApiConfig(`${adminPasswordReference.env} must contain at least 12 characters`),
    )
  })

const validateApiSecrets = (
  config: S0ResolvedConfig,
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
  mcpcfProxySigningSecret: ApiSecretInput,
) =>
  Result.gen(function* () {
    yield* Match.value(credentialSignInEnabled(config.auth)).pipe(
      Match.when(true, () => validateCredentialSignIn(config, secretBindings)),
      Match.orElse(() => Result.void),
    )

    yield* ensureConfig(
      hasMinimumLength(mcpcfProxySigningSecret, MCPCF_PROXY_SIGNING_SECRET_MIN_LENGTH),
      () =>
        invalidApiConfig(
          `${config.security.mcpcfProxySigningSecret.env} must contain at least ${MCPCF_PROXY_SIGNING_SECRET_MIN_LENGTH} characters`,
        ),
    )
  })

function githubAppEnv(
  githubApp: S0ResolvedConfig["integrations"]["githubApp"],
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
): Pick<
  ApiInfraEnv,
  | "GITHUB_APP_CLIENT_ID"
  | "GITHUB_APP_CLIENT_SECRET"
  | "GITHUB_APP_ID"
  | "GITHUB_APP_PRIVATE_KEY"
  | "GITHUB_APP_SLUG"
  | "GITHUB_APP_WEBHOOK_SECRET"
> {
  return Match.value(githubApp.enabled).pipe(
    Match.when(true, () => ({
      GITHUB_APP_CLIENT_ID: githubApp.clientId,
      GITHUB_APP_CLIENT_SECRET: secretValue(secretBindings, githubApp.clientSecret),
      GITHUB_APP_ID: githubApp.appId,
      GITHUB_APP_PRIVATE_KEY: secretValue(secretBindings, githubApp.privateKey),
      GITHUB_APP_SLUG: githubApp.slug,
      GITHUB_APP_WEBHOOK_SECRET: secretValue(secretBindings, githubApp.webhookSecret),
    })),
    Match.orElse(() => ({
      GITHUB_APP_CLIENT_ID: "",
      GITHUB_APP_CLIENT_SECRET: "",
      GITHUB_APP_ID: "",
      GITHUB_APP_PRIVATE_KEY: "",
      GITHUB_APP_SLUG: "",
      GITHUB_APP_WEBHOOK_SECRET: "",
    })),
  )
}

export function getApiInfraEnv(
  config: S0ResolvedConfig,
  configurationFile: string,
  deploymentConfigDigest: string,
  secretBindings: Readonly<Record<string, ApiSecretInput>>,
): ApiInfraEnv {
  const mcpcfProxySigningSecret = secretValue(
    secretBindings,
    config.security.mcpcfProxySigningSecret,
  )

  // oxlint-disable-next-line effect/avoid-option-getorthrow -- Synchronous boundary for non-Effect callers: invalid input throws the typed error by contract.
  Result.getOrThrow(validateApiSecrets(config, secretBindings, mcpcfProxySigningSecret))

  const slack = config.integrations.slack

  const configSecretBindings = Object.fromEntries(
    s0RuntimeSecretReferences(config).map((reference) => [
      reference.env,
      secretValue(secretBindings, reference),
    ]),
  )

  const cloudflareAiGatewayProviderKeySecrets = Object.fromEntries(
    Object.entries(config.aiProviders.cloudflareAiGateway.providerKeys ?? {}).map(
      ([providerId, reference]) => [providerId, secretValue(secretBindings, reference)],
    ),
  )

  const optionalConfig = includeWhenDefined(
    includeWhenDefined(
      {
        S0_PROVIDER_LAYER: "live" as const,
        S0_AI_GATEWAY_LAYER: config.aiGatewayLayer ?? "live",
        S0_CONFIG_FILE: configurationFile,
        S0_BRAND_NAME: config.brand.name,
        S0_SERVICE_NAME: `${config.deployment.appName}-agent-control-plane`,
        S0_CREATE_PR_COMMAND:
          config.integrations.githubApp.createPullRequestCommand ?? "s0-create-pr",
        S0_CONFIG_ADMIN: config.admins,
        S0_CONFIG_AUTH: config.auth,
        S0_CONFIG_CLOUDFLARE_AI_GATEWAY: config.aiProviders.cloudflareAiGateway,
      },
      config.aiProviders.litellm,
      (litellm) => ({ S0_CONFIG_LITELLM: litellm }),
    ),
    config.mcpcf,
    (mcpcf) => ({ S0_CONFIG_MCPCF: mcpcf }),
  )

  const slackToken = secretValue(
    secretBindings,
    Option.getOrUndefined(Option.liftPredicate(slack.botToken, () => slack.enabled)),
  )

  return {
    ...optionalConfig,
    S0_DEPLOYMENT_CONFIG_DIGEST: deploymentConfigDigest,
    configSecretBindings,
    cloudflareAiGatewayProviderKeySecrets,
    MCPCF_PROXY_SIGNING_SECRET: mcpcfProxySigningSecret,
    TOKEN_ENCRYPTION_KEY: secretValue(secretBindings, config.security.tokenEncryptionKey),
    REPO_SECRETS_ENCRYPTION_KEY: secretValue(
      secretBindings,
      config.security.repositorySecretsEncryptionKey,
    ),
    BETTER_AUTH_SECRET: secretValue(secretBindings, config.security.betterAuthSecret),
    ...githubAppEnv(config.integrations.githubApp, secretBindings),
    SLACK_TOKEN: slackToken,
    CF_AI_SEARCH_SERVICE_TOKEN_ID: configuredStringSecretValue(
      secretBindings,
      config.aiSearch.serviceTokenId,
    ),
  }
}

